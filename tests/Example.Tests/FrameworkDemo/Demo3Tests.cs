#nullable enable

using FluentAssertions;
using Fuookami.Ospf.Example.FrameworkDemo.Demo3;
using Fuookami.Ospf.Utils.Error;
using Fuookami.Ospf.Utils.Functional;
using System.Linq;
using Xunit;

namespace Fuookami.Ospf.Example.Tests.FrameworkDemo;

public class Demo3ColumnGenerationTests {
    [Fact]
    public void BuildModel_ShouldSucceed() {
        var demo = new ColumnGenerationDemo();
        Result<Success, ErrorCode, Error<ErrorCode>> result = demo.BuildModel();
        result.Should().BeOfType<Ok<Success, Fuookami.Ospf.Utils.Error.ErrorCode, Fuookami.Ospf.Utils.Error.Error<Fuookami.Ospf.Utils.Error.ErrorCode>>>();
    }

    [Fact]
    public void Model_ShouldHaveMinimumObjective() {
        var demo = new ColumnGenerationDemo();
        demo.BuildModel();
        demo.MetaModel.ObjectCategory.Should().Be(Fuookami.Ospf.Core.Model.Basic.ObjectCategory.Minimum);
    }

    [Fact]
    public void Model_ShouldHaveDemandConstraints() {
        var demo = new ColumnGenerationDemo();
        demo.BuildModel();
        // 4 demand constraints
        demo.MetaModel.RelationConstraints.Count.Should().BeGreaterThanOrEqualTo(4);
    }

    [Fact]
    public void Patterns_ShouldBeGenerated() {
        var demo = new ColumnGenerationDemo();
        demo.BuildModel();
        demo.Patterns.Should().NotBeEmpty();
    }

    /// <summary>**至少一条模式必须同时装两种产品** / At least one pattern must mix two products.</summary>
    /// <remarks>
    /// **这是这里唯一能区分"用框架生成"和"手写生成"的判据。**
    ///
    /// 之前手写的逻辑是：
    ///
    /// ```csharp
    /// quantities[d] = (int)(RawLength / Demands[d].Width);
    /// ```
    ///
    /// 每条模式**只有一个非零产品**。而 `FullSumGenerator` 会在一条模式里组合多个宽度。
    /// 所以"存在一条多产品模式"直接证明了框架真的在跑。
    ///
    /// **若有人把手写版本改回来**，其余四条测试**仍然全部通过**（模式仍然非空、约束仍然成立），
    /// 只有这条会失败。
    ///
    /// **This is the only criterion separating "generated by the framework" from "hand-written"**. The pre- code above produced patterns with **exactly one
    /// non-zero product**, whereas `FullSumGenerator` combines several widths in one pattern. So "a multi-product pattern exists" directly proves the framework ran.
    ///
    /// **If anyone reverts to the hand-written version**, the other four tests **still pass** (patterns remain non-empty, constraints still hold); only this one
    /// fails.
    /// </remarks>
    [Fact]
    public void AtLeastOnePattern_ShouldMixSeveralProducts() {
        var demo = new ColumnGenerationDemo();
        demo.BuildModel();

        demo.Patterns.Should().Contain(
            pattern => pattern.Quantities.Count(quantity => quantity > 0) >= 2,
            "the hand-written version could never produce a mixed pattern");
    }

    /// <summary>**每条模式都不得超过原料长度** / Every pattern must fit the raw length.</summary>
    /// <remarks>
    /// 手写版本靠 `floor` 保证不超长；框架版本靠搜索保证。**若生成器漏掉宽度上界检查，
    /// 超长模式会混进主问题**，而模式数量仍然"看起来合理"。
    ///
    /// The hand-written version relied on `floor` to stay within bounds; the framework version relies on the search. **If the generator missed the width bound,
    /// over-long patterns would enter the master** while the pattern count still looked plausible.
    /// </remarks>
    [Fact]
    public void EveryPattern_ShouldFitTheRawLength() {
        var demo = new ColumnGenerationDemo();
        demo.BuildModel();

        double rawLength = 1000.0;
        foreach (CuttingPattern pattern in demo.Patterns) {
            double used = 0.0;
            for (int index = 0; index < pattern.Quantities.Count; ++index) {
                used += pattern.Quantities[index] * DemoWidths[index];
            }
            used.Should().BeLessThanOrEqualTo(rawLength, "pattern {0} exceeds the raw length", pattern.Index);
        }
    }

    /// <summary>**每条模式都必须装到东西** / Every pattern must carry at least one product.</summary>
    [Fact]
    public void EveryPattern_ShouldCarryAtLeastOneProduct() {
        var demo = new ColumnGenerationDemo();
        demo.BuildModel();

        demo.Patterns.Should().OnlyContain(pattern => pattern.Quantities.Any(quantity => quantity > 0));
    }

    /// <summary>演示里四个需求的宽度，测试用它重算用量 / The four demand widths, used by the tests to recompute usage.</summary>
    private static readonly double[] DemoWidths = { 450.0, 360.0, 310.0, 140.0 };
}
